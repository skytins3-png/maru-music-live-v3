package com.maru.radio;

import android.content.Context;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.speech.tts.TextToSpeech;
import android.speech.tts.UtteranceProgressListener;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.util.ArrayDeque;
import java.util.Locale;
import java.util.function.Consumer;

/** TTS -> ephemeral local PCM WAV -> direct AAC mixer, with NO speaker playback. */
public final class RadioRtmpTtsBridge {
    private final Context app;
    private final Handler handler = new Handler(Looper.getMainLooper());
    private final ArrayDeque<RadioDjLanguagePolicy.Line> waiting = new ArrayDeque<>();
    private final Consumer<short[]> receiver;
    private final int outputRate;
    private TextToSpeech tts;
    private boolean ready, busy, closed;
    private int id;
    private File temporary;

    public RadioRtmpTtsBridge(Context appContext, int sampleRate, Consumer<short[]> pcmSink) {
        app = appContext.getApplicationContext();
        outputRate = sampleRate;
        receiver = pcmSink;
        tts = new TextToSpeech(app, result -> handler.post(() -> {
            ready = result == TextToSpeech.SUCCESS && tts != null;
            if (!ready) { waiting.clear(); return; }
            tts.setSpeechRate(.93f);
            tts.setPitch(.96f);
            dispatch();
        }));
    }

    public void offer(RadioDjLanguagePolicy.Line line) {
        if (line == null || line.text == null || line.text.isEmpty()
                || line.text.length() > 200 || closed) return;
        handler.post(() -> {
            if (closed || waiting.size() >= 5) return;
            waiting.addLast(line);
            dispatch();
        });
    }

    private void dispatch() {
        if (closed || busy || !ready || waiting.isEmpty() || tts == null) return;
        RadioDjLanguagePolicy.Line line = waiting.removeFirst();
        Locale[] locales = {Locale.KOREAN, Locale.SIMPLIFIED_CHINESE, Locale.US,
                Locale.JAPANESE, new Locale("ru", "RU")};
        int language = Math.max(0, Math.min(4, line.language));
        int supported = tts.setLanguage(locales[language]);
        if (supported == TextToSpeech.LANG_MISSING_DATA
                || supported == TextToSpeech.LANG_NOT_SUPPORTED) {
            handler.post(this::dispatch);
            return;
        }
        busy = true;
        int ticket = ++id;
        File wav = new File(app.getCacheDir(), "maru-private-rtmp-tts-" + ticket + ".wav");
        temporary = wav;
        tts.setOnUtteranceProgressListener(new UtteranceProgressListener() {
            @Override public void onStart(String ignored) {}
            @Override public void onDone(String name) {
                if (!name.equals("maru-rtmp-" + ticket)) return;
                handler.post(() -> {
                    if (!closed && id == ticket) {
                        short[] samples = readWav(wav, outputRate);
                        if (samples != null) receiver.accept(samples);
                    }
                    finish(wav, ticket);
                });
            }
            @Override public void onError(String name) {
                if (name.equals("maru-rtmp-" + ticket))
                    handler.post(() -> finish(wav, ticket));
            }
        });
        try {
            if (tts.synthesizeToFile(line.text, new Bundle(), wav,
                    "maru-rtmp-" + ticket) == TextToSpeech.ERROR) finish(wav, ticket);
        } catch (RuntimeException e) { finish(wav, ticket); }
    }

    private void finish(File wav, int ticket) {
        if (wav.exists()) wav.delete();
        if (ticket != id) return;
        temporary = null;
        busy = false;
        dispatch();
    }

    private static int u16(byte[] b, int p) {
        return (b[p]&255) | ((b[p+1]&255)<<8);
    }
    private static int u32(byte[] b, int p) {
        return u16(b,p) | (u16(b,p+2)<<16);
    }

    /** Decode 16-bit little-endian PCM WAV generated by Android TTS. */
    static short[] readWav(File f, int rate) {
        if (f == null || !f.isFile() || f.length() > 7_000_000L) return null;
        try (FileInputStream in = new FileInputStream(f);
             ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            byte[] buf = new byte[8192];
            for(int n;(n=in.read(buf))>=0;) {
                out.write(buf,0,n);
                if (out.size() > 7_000_000) return null;
            }
            byte[] b = out.toByteArray();
            if (b.length < 44 || b[0]!='R'||b[1]!='I'||b[2]!='F'||b[3]!='F'
                    || b[8]!='W'||b[9]!='A'||b[10]!='V'||b[11]!='E') return null;
            int channels=0, sourceRate=0, bits=0, encoding=0, data=-1, len=0;
            for (int p=12;p+8<=b.length;) {
                int n=u32(b,p+4);
                if(n<0||n>b.length-p-8)return null;
                String tag=new String(b,p,4,java.nio.charset.StandardCharsets.US_ASCII);
                if ("fmt ".equals(tag) && n>=16) {
                    encoding=u16(b,p+8);channels=u16(b,p+10);
                    sourceRate=u32(b,p+12);bits=u16(b,p+22);
                } else if ("data".equals(tag)){data=p+8;len=n;}
                p+=8+n+(n&1);
            }
            if (encoding!=1 || bits!=16 || channels<1 || channels>2 ||
                    sourceRate<8000 || sourceRate>96000 || rate<8000 ||
                    rate>96000 || data<0 || len<channels*2) return null;
            int frames=len/(channels*2);
            int count=(int)Math.min((long)rate*25, (long)frames*rate/sourceRate);
            short[] samples=new short[count];
            for(int i=0;i<count;i++) {
                int index=(int)Math.min(frames-1,(long)i*sourceRate/rate);
                int p=data+index*channels*2;
                int mono=(short)u16(b,p);
                if(channels==2)mono=(mono+(short)u16(b,p+2))/2;
                samples[i]=(short)mono;
            }
            return samples;
        } catch(Exception e) { return null; }
    }

    public void close() {
        closed = true; id++; waiting.clear();
        if(tts!=null)try{tts.stop();tts.shutdown();}catch(RuntimeException ignored){}
        tts=null;
        if(temporary!=null&&temporary.exists())temporary.delete();
        temporary=null;
    }
}
